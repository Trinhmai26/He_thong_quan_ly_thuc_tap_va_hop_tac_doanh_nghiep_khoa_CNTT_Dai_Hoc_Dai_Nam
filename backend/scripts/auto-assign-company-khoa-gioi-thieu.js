/**
 * Script: auto-assign-company-khoa-gioi-thieu.js
 *
 * Cách chạy:
 *   cd backend
 *   node scripts/auto-assign-company-khoa-gioi-thieu.js
 *
 * Tính năng:
 *   - Tự động gán 80 doanh nghiệp cho sinh viên "Khoa giới thiệu" chưa có DN (round-robin)
 *   - Cập nhật dang_ky_thuc_tap_sinh_vien → trang_thai='da-duyet', workflow_status_v2='APPROVED'
 *   - Gửi thông báo trong hệ thống (chống trùng lặp)
 *   - Gửi email cho sinh viên (bỏ qua email tự sinh dạng số)
 *   - Log chi tiết toàn bộ quá trình
 *   - Idempotent: chạy nhiều lần không gây nhân đôi dữ liệu
 *
 * Không ảnh hưởng đến:
 *   - Sinh viên chưa đăng ký / chưa chọn nguyện vọng
 *   - Sinh viên "Tự liên hệ"
 *   - Sinh viên đã có doanh nghiệp
 *   - Sinh viên bị từ chối
 *   - Toàn bộ logic cũ: phân công GV, chọn đợt, import/export
 */

'use strict';

require('dotenv').config({ path: require('path').join(__dirname, '../.env') });

const connection = require('../src/database/connection');
const { createNotification, ensureNotificationsTable } = require('../src/utils/notificationHelper');
const { sendKhoaGioiThieuAssignmentEmail } = require('../src/services/EmailService');

// ─── Màu terminal ────────────────────────────────────────────────────────────
const C = {
  reset: '\x1b[0m', bold: '\x1b[1m',
  green: '\x1b[32m', red: '\x1b[31m', yellow: '\x1b[33m',
  cyan: '\x1b[36m', gray: '\x1b[90m', blue: '\x1b[34m'
};
const ok  = (s) => `${C.green}✓${C.reset} ${s}`;
const err = (s) => `${C.red}✗${C.reset} ${s}`;
const warn = (s) => `${C.yellow}⚠${C.reset} ${s}`;
const info = (s) => `${C.cyan}ℹ${C.reset} ${s}`;
const sep  = () => console.log(`${C.gray}${'─'.repeat(64)}${C.reset}`);

// ─── Kiểm tra email tự sinh (format: chỉ số @domain) ────────────────────────
function isAutoGeneratedEmail(email) {
  return !email || /^\d+@[a-zA-Z0-9.-]+\.[a-zA-Z]{2,}$/.test(email.trim());
}

async function run() {
  console.log(`\n${C.bold}${C.blue}╔══ AUTO-ASSIGN DOANH NGHIỆP → KHOA GIỚI THIỆU ══╗${C.reset}`);
  console.log(`${C.gray}Thời điểm: ${new Date().toLocaleString('vi-VN')}${C.reset}\n`);

  // ── BƯỚC 1: Kiểm tra doanh nghiệp ─────────────────────────────────────────
  sep();
  console.log(info('BƯỚC 1: Lấy danh sách doanh nghiệp...'));

  const companies = await connection.query(
    `SELECT id, ten_cong_ty, so_luong_nhan_thuc_tap
     FROM doanh_nghiep
     WHERE ten_cong_ty IS NOT NULL AND ten_cong_ty != ''
     ORDER BY id ASC`,
    []
  );

  if (!companies || companies.length === 0) {
    console.log(err('Không có doanh nghiệp nào trong database. Vui lòng thêm doanh nghiệp trước.'));
    process.exit(1);
  }

  console.log(ok(`Tổng số doanh nghiệp: ${C.bold}${companies.length}${C.reset}`));
  companies.forEach((c, i) => {
    const cap = Number(c.so_luong_nhan_thuc_tap) > 0 ? `(tối đa ${c.so_luong_nhan_thuc_tap} SV)` : '(không giới hạn)';
    console.log(`   ${C.gray}${i + 1}.${C.reset} ${c.ten_cong_ty} ${C.gray}${cap}${C.reset}`);
  });

  // ── BƯỚC 2: Kiểm tra sinh viên ────────────────────────────────────────────
  sep();
  console.log(info('BƯỚC 2: Lấy danh sách sinh viên đủ điều kiện...'));

  // Hỗ trợ cả 'khoa_gioi_thieu' (underscore, UI form) VÀ 'khoa-gioi-thieu' (hyphen, ExcelImportService)
  const students = await connection.query(
    `SELECT sv.id, sv.account_id, sv.ho_ten, sv.ma_sinh_vien, sv.email_ca_nhan,
            sv.vi_tri_muon_ung_tuyen_thuc_tap
     FROM sinh_vien sv
     WHERE sv.nguyen_vong_thuc_tap IN ('khoa_gioi_thieu', 'khoa-gioi-thieu')
       AND (sv.don_vi_thuc_tap IS NULL OR sv.don_vi_thuc_tap = '')
       AND NOT EXISTS (
         SELECT 1 FROM dang_ky_thuc_tap_sinh_vien dk
         WHERE dk.sinh_vien_id = sv.id
           AND dk.workflow_status_v2 IN ('REJECTED','FAIL')
           AND dk.id = (SELECT MAX(dk2.id) FROM dang_ky_thuc_tap_sinh_vien dk2 WHERE dk2.sinh_vien_id = sv.id)
       )
     ORDER BY sv.id`,
    []
  );

  // Sinh viên khoa_gioi_thieu đã có DN (bỏ qua) — cả hai format
  const alreadyHas = await connection.query(
    `SELECT COUNT(*) AS cnt FROM sinh_vien
     WHERE nguyen_vong_thuc_tap IN ('khoa_gioi_thieu', 'khoa-gioi-thieu')
       AND don_vi_thuc_tap IS NOT NULL AND don_vi_thuc_tap != ''`,
    []
  );

  // Tổng sinh viên chưa chọn nguyện vọng
  const noPreference = await connection.query(
    `SELECT COUNT(*) AS cnt FROM sinh_vien
     WHERE nguyen_vong_thuc_tap IS NULL OR nguyen_vong_thuc_tap = ''`,
    []
  );

  console.log(ok(`Sinh viên đủ điều kiện (sẽ gán):         ${C.bold}${students.length}${C.reset}`));
  console.log(warn(`Bỏ qua – đã có doanh nghiệp:             ${alreadyHas[0]?.cnt || 0}`));
  console.log(warn(`Bỏ qua – chưa chọn nguyện vọng:          ${noPreference[0]?.cnt || 0}`));

  if (students.length === 0) {
    console.log(`\n${ok('Không có sinh viên nào cần gán. Kết thúc.')}\n`);
    process.exit(0);
  }

  // ── BƯỚC 3: Gán doanh nghiệp round-robin ──────────────────────────────────
  sep();
  console.log(info(`BƯỚC 3: Gán doanh nghiệp cho ${students.length} sinh viên (round-robin)...\n`));

  const pool = companies.map(c => ({
    ten_cong_ty: c.ten_cong_ty,
    capacity: Number(c.so_luong_nhan_thuc_tap) > 0 ? Number(c.so_luong_nhan_thuc_tap) : 0,
    assigned: 0
  }));

  await ensureNotificationsTable();
  const now = new Date();

  const report = {
    assigned:       [],
    notif_created:  [],
    notif_skipped:  [],
    email_sent:     [],
    email_skipped:  [],
    email_failed:   [],
    errors:         []
  };

  let poolIdx = 0;

  for (const sv of students) {
    // Tìm công ty còn slot
    let loops = 0;
    while (
      loops < pool.length &&
      pool[poolIdx % pool.length].capacity > 0 &&
      pool[poolIdx % pool.length].assigned >= pool[poolIdx % pool.length].capacity
    ) { poolIdx++; loops++; }

    const company = pool[poolIdx % pool.length];
    company.assigned++;
    poolIdx++;

    const viTri = sv.vi_tri_muon_ung_tuyen_thuc_tap || '';

    try {
      // 3a. Cập nhật sinh_vien.don_vi_thuc_tap
      await connection.query(
        `UPDATE sinh_vien SET don_vi_thuc_tap = ?, updated_at = NOW() WHERE id = ?`,
        [company.ten_cong_ty, sv.id]
      );

      // 3b. Upsert dang_ky_thuc_tap_sinh_vien
      const existing = await connection.query(
        'SELECT id FROM dang_ky_thuc_tap_sinh_vien WHERE sinh_vien_id = ? ORDER BY id DESC LIMIT 1',
        [sv.id]
      );

      const upsert = async (withV2) => {
        if (existing && existing.length > 0) {
          const sql = withV2
            ? `UPDATE dang_ky_thuc_tap_sinh_vien
               SET trang_thai = 'da-duyet', workflow_status_v2 = 'APPROVED',
                   nguyen_vong_thuc_tap = 'khoa-gioi-thieu',
                   ten_cong_ty = ?, vi_tri_thuc_tap_mong_muon = ?,
                   ngay_duyet = ?, updated_at = NOW()
               WHERE id = ?`
            : `UPDATE dang_ky_thuc_tap_sinh_vien
               SET trang_thai = 'da-duyet', nguyen_vong_thuc_tap = 'khoa-gioi-thieu',
                   ten_cong_ty = ?, vi_tri_thuc_tap_mong_muon = ?,
                   ngay_duyet = ?, updated_at = NOW()
               WHERE id = ?`;
          await connection.query(sql, [company.ten_cong_ty, viTri, now, existing[0].id]);
        } else {
          const sql = withV2
            ? `INSERT INTO dang_ky_thuc_tap_sinh_vien
                 (sinh_vien_id, nguyen_vong_thuc_tap, vi_tri_thuc_tap_mong_muon, ten_cong_ty,
                  trang_thai, workflow_status_v2, ngay_duyet, created_at, updated_at)
               VALUES (?, 'khoa-gioi-thieu', ?, ?, 'da-duyet', 'APPROVED', ?, NOW(), NOW())`
            : `INSERT INTO dang_ky_thuc_tap_sinh_vien
                 (sinh_vien_id, nguyen_vong_thuc_tap, vi_tri_thuc_tap_mong_muon, ten_cong_ty,
                  trang_thai, ngay_duyet, created_at, updated_at)
               VALUES (?, 'khoa-gioi-thieu', ?, ?, 'da-duyet', ?, NOW(), NOW())`;
          await connection.query(sql, [sv.id, viTri, company.ten_cong_ty, now]);
        }
      };

      try { await upsert(true); }
      catch (colErr) {
        if (colErr?.code !== 'ER_BAD_FIELD_ERROR' && colErr?.errno !== 1054) throw colErr;
        await upsert(false);
      }

      report.assigned.push({ ma: sv.ma_sinh_vien, ten: sv.ho_ten, dn: company.ten_cong_ty });
      console.log(ok(`${sv.ma_sinh_vien} | ${sv.ho_ten} → ${C.green}${company.ten_cong_ty}${C.reset}`));

    } catch (assignErr) {
      report.errors.push({ ma: sv.ma_sinh_vien, error: assignErr.message });
      console.log(err(`${sv.ma_sinh_vien} | ${sv.ho_ten} — lỗi gán: ${assignErr.message}`));
      continue;
    }

    // 3c. Thông báo trong hệ thống (chống trùng lặp)
    if (sv.account_id) {
      try {
        const dup = await connection.query(
          `SELECT id FROM notifications
           WHERE receiver_id = ? AND action_type = 'company_auto_assigned'
           LIMIT 1`,
          [sv.account_id]
        );

        if (!dup || dup.length === 0) {
          await createNotification(
            sv.account_id,
            'Thông báo doanh nghiệp thực tập',
            `Bạn đã được khoa giới thiệu doanh nghiệp thực tập: ${company.ten_cong_ty}. Hồ sơ của bạn đã được chuyển sang bước Doanh nghiệp phỏng vấn. Vui lòng theo dõi thông báo tiếp theo.`,
            'success',
            'company_auto_assigned'
          );
          report.notif_created.push(sv.ma_sinh_vien);
        } else {
          report.notif_skipped.push(sv.ma_sinh_vien);
        }
      } catch (notifErr) {
        console.log(warn(`  Thông báo SV ${sv.ma_sinh_vien}: ${notifErr.message}`));
      }
    }

    // 3d. Gửi email
    if (!isAutoGeneratedEmail(sv.email_ca_nhan)) {
      try {
        const result = await sendKhoaGioiThieuAssignmentEmail({
          studentEmail: sv.email_ca_nhan,
          studentName:  sv.ho_ten || '',
          studentCode:  sv.ma_sinh_vien || '',
          companyName:  company.ten_cong_ty,
          position:     viTri
        });
        if (result?.skipped) {
          report.email_skipped.push(sv.email_ca_nhan);
        } else {
          report.email_sent.push(sv.email_ca_nhan);
          console.log(`   ${C.gray}📧 Email gửi OK → ${sv.email_ca_nhan}${C.reset}`);
        }
      } catch (mailErr) {
        report.email_failed.push({ email: sv.email_ca_nhan, error: mailErr.message });
        console.log(warn(`  Email lỗi (${sv.email_ca_nhan}): ${mailErr.message}`));
      }
    } else {
      report.email_skipped.push(sv.email_ca_nhan || '(không có email)');
    }
  }

  // ── BÁO CÁO KẾT QUẢ ───────────────────────────────────────────────────────
  sep();
  console.log(`\n${C.bold}${C.green}═══ KẾT QUẢ ═══${C.reset}`);
  console.log(`${C.bold}  Tổng DN trong hệ thống:       ${companies.length}${C.reset}`);
  console.log(`${C.bold}  Sinh viên đủ điều kiện:        ${students.length}${C.reset}`);
  console.log(`${C.green}  Sinh viên đã gán thành công:  ${report.assigned.length}${C.reset}`);
  console.log(`${C.yellow}  Bỏ qua (đã có DN trước):      ${alreadyHas[0]?.cnt || 0}${C.reset}`);
  console.log(`${C.red}  Lỗi:                          ${report.errors.length}${C.reset}`);
  console.log(`\n${C.cyan}  Thông báo tạo mới:            ${report.notif_created.length}${C.reset}`);
  console.log(`${C.gray}  Thông báo bỏ qua (trùng):     ${report.notif_skipped.length}${C.reset}`);
  console.log(`\n${C.cyan}  Email gửi thành công:         ${report.email_sent.length}${C.reset}`);
  console.log(`${C.gray}  Email bỏ qua (tự sinh/trống): ${report.email_skipped.length}${C.reset}`);
  console.log(`${C.red}  Email lỗi:                    ${report.email_failed.length}${C.reset}`);

  if (report.email_failed.length > 0) {
    console.log(`\n${C.red}Chi tiết email lỗi:${C.reset}`);
    report.email_failed.forEach(f => console.log(`  - ${f.email}: ${f.error}`));
  }

  if (report.errors.length > 0) {
    console.log(`\n${C.red}Chi tiết lỗi gán:${C.reset}`);
    report.errors.forEach(e => console.log(`  - ${e.ma}: ${e.error}`));
  }

  // ── BƯỚC 4: Xác minh kết quả trong DB ─────────────────────────────────────
  sep();
  console.log(info('BƯỚC 4: Xác minh kết quả (10 bản ghi đầu)...\n'));

  const verify = await connection.query(
    `SELECT sv.ma_sinh_vien, sv.ho_ten,
            sv.don_vi_thuc_tap,
            dk.trang_thai,
            dk.workflow_status_v2
     FROM sinh_vien sv
     LEFT JOIN (
       SELECT sinh_vien_id, trang_thai, workflow_status_v2
       FROM dang_ky_thuc_tap_sinh_vien
       WHERE id IN (SELECT MAX(id) FROM dang_ky_thuc_tap_sinh_vien GROUP BY sinh_vien_id)
     ) dk ON dk.sinh_vien_id = sv.id
     WHERE sv.nguyen_vong_thuc_tap = 'khoa_gioi_thieu'
       AND sv.don_vi_thuc_tap IS NOT NULL AND sv.don_vi_thuc_tap != ''
     ORDER BY sv.ma_sinh_vien
     LIMIT 10`,
    []
  );

  console.log(`${'Mã SV'.padEnd(14)} | ${'Họ tên'.padEnd(24)} | ${'Doanh nghiệp'.padEnd(28)} | Trạng thái`);
  console.log('─'.repeat(90));
  verify.forEach(r => {
    console.log(
      `${(r.ma_sinh_vien || '').padEnd(14)} | ` +
      `${(r.ho_ten || '').substring(0, 24).padEnd(24)} | ` +
      `${(r.don_vi_thuc_tap || '').substring(0, 28).padEnd(28)} | ` +
      `${r.workflow_status_v2 || r.trang_thai || 'NULL'}`
    );
  });

  console.log(`\n${C.green}${C.bold}Hoàn tất!${C.reset} Khởi động lại backend và F5 trang admin để xem kết quả.\n`);
  process.exit(0);
}

run().catch(e => {
  console.error(err('Lỗi nghiêm trọng:'), e.message);
  process.exit(1);
});
